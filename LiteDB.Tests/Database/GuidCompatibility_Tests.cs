            "AAAA==";

        private static readonly Guid ExpectedId =
            new Guid("00112233-4455-6677-8899-aabbccddeeff");

        private static readonly Guid ExpectedValue =
            new Guid("fedcba98-7654-3210-0123-456789abcdef");

        [Fact]
        public void Guid_values_written_before_span_serialization_are_read_unchanged()
        {
            // Generated by LiteDB at the PR merge base a50661a9, before the
            // span-based Guid reader and writer existed.
            using (var databaseStream = DecompressDatabase())
            using (var database = new LiteDatabase(databaseStream))
            {
                var document = database.GetCollection("guids").FindById(ExpectedId);

                Assert.NotNull(document);
                document["_id"].AsGuid.Should().Be(ExpectedId);
                document["value"].AsGuid.Should().Be(ExpectedValue);
                document["label"].AsString.Should().Be("written-before-pr");
            }
        }

        private static MemoryStream DecompressDatabase()
        {
            var compressedBytes = Convert.FromBase64String(PreSpanSerializationDatabaseGzipBase64);
            var compressedStream = new MemoryStream(compressedBytes);
            var databaseStream = new MemoryStream();

            using (compressedStream)
            using (var gzipStream = new GZipStream(compressedStream, CompressionMode.Decompress))
            {
                gzipStream.CopyTo(databaseStream);
            }

            databaseStream.Position = 0;

            return databaseStream;
        }
    }
